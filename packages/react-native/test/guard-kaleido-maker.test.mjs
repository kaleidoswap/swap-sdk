/**
 * Run the patched module with stand-ins for the native side, and return its
 * `SwapClient` plus the calls that reached the native constructor.
 */
function loadGuarded() {
  const source = stripTypeScriptTypes(
    guardKaleidoMaker(GENERATED)
      .replace(/^(?:import|export type) [\s\S]*?from "[^"]+";\n/gm, "")
      .replace(/^export /gm, ""),
  );
  const nativeCalls = [];
  const identity = { lower: (value) => value, lift: (value) => value };
  const Exception = {
    Generic: class Generic extends Error {
      tag = "Generic";
      constructor(message) {
        super(message);
        this.inner = [message];
      }
    },
  };
  const stubs = {
    kaleidoMakerRefusal,
    Exception,
    UniffiAbstractObject: class {},
    FfiConverterTypeSwapClient: identity,
    FfiConverterTypeError: identity,
    FfiConverterString: identity,
    FfiConverterOptionalUInt64: identity,
    uniffiCaller: { rustCallWithError: (_liftError, caller) => caller({}) },
    nativeModule: () => ({
      ubrn_uniffi_kaleidorg_swap_sdk_fn_constructor_swapclient_kaleido_maker: (...args) => {
        nativeCalls.push(args.slice(0, 3));
        return "client";
      },
    }),
  };
  const SwapClient = new Function(...Object.keys(stubs), `${source}\nreturn SwapClient;`)(
    ...Object.values(stubs),
  );
  return { SwapClient, Exception, nativeCalls };
}

test("kaleidoMaker is refused without the opt-in, before the key reaches native code", () => {
  const { SwapClient, Exception, nativeCalls } = loadGuarded();
  for (const options of [
    undefined,
    {},
    { allowMobile: false },
    // Only the boolean counts, so a stray string from configuration cannot
    // switch the refusal off.
    { allowMobile: "true" },
    { allowMobile: 1 },
  ]) {
    assert.throws(
      () => SwapClient.kaleidoMaker("https://maker.example", API_KEY, undefined, options),
      (error) =>
        error instanceof Exception.Generic &&
        error.message === KALEIDO_MAKER_IN_APP_REFUSAL &&
        !error.message.includes(API_KEY),
      `kaleidoMaker should be refused with ${JSON.stringify(options)}`,
    );
  }
  assert.deepEqual(nativeCalls, []);
});

test("kaleidoMaker builds with allowMobile: true", () => {
  const { SwapClient, nativeCalls } = loadGuarded();
  assert.equal(
    SwapClient.kaleidoMaker("https://maker.example", API_KEY, 30n, { allowMobile: true }),
    "client",
  );
  assert.deepEqual(nativeCalls, [["https://maker.example", API_KEY, 30n]]);
});

test("the refusal names the opt-in and never the key", () => {
  assert.equal(kaleidoMakerRefusal({ allowMobile: true }), undefined);
  assert.match(KALEIDO_MAKER_IN_APP_REFUSAL, /allowMobile: true/);
  assert.match(KALEIDO_MAKER_IN_APP_REFUSAL, /mobile app/);
});

test("adds the import, the parameter and the refusal", () => {
  const guarded = guardKaleidoMaker(GENERATED);
  assert.ok(isGuarded(guarded));
  assert.ok(!isGuarded(GENERATED));
  assert.match(
    guarded,
    /public static kaleidoMaker\(makerUrl: string, apiKey: string, timeout: \/\*u64\*\/bigint \| undefined, options\?: KaleidoMakerAppOptions\): SwapClientInterface \/\*throws\*\/ \{\n {4}const refusal = kaleidoMakerRefusal\(options\);/,
  );
  // The import goes beside the generated ones, below the header comment.
  assert.ok(
    guarded.indexOf('from "../kaleido-maker-guard"') < guarded.indexOf("import nativeModule"),
  );
  assert.ok(guarded.startsWith("// This file was autogenerated"));
});

test("patching twice changes nothing", () => {
  const once = guardKaleidoMaker(GENERATED);
  assert.equal(guardKaleidoMaker(once), once);
});

// A generator that renamed or reshaped the method would otherwise ship the
// secret-key constructor unguarded, so these stop the build.
test("refuses a file without kaleidoMaker", () => {
  assert.throws(
    () => guardKaleidoMaker(GENERATED.replace("kaleidoMaker(", "kaleidoMakerV2(")),
    /found 0/,
  );
});

test("refuses a file with two kaleidoMaker methods", () => {
  const twice = GENERATED.replace(
    /public static kaleidoMaker\([^]*?\n {4}\}\n/,
    (method) => method + method,
  );
  assert.throws(() => guardKaleidoMaker(twice), /found 2/);
});

test("refuses a partly guarded file", () => {
  const partial = guardKaleidoMaker(GENERATED).replace(/\n {4}if \(refusal[^\n]*/, "");
  assert.throws(() => guardKaleidoMaker(partial), /partly guarded/);
});
