//! Emit the actual serde DTO surface, with the WASM serializer's integer types.

use kaleidorg_swap_sdk::boltz::*;
use kaleidorg_swap_sdk::swaps::rgb::RgbLock;
use std::collections::HashSet;
use ts_rs::{Config, TS};

fn assert_complete(emitted: &HashSet<String>, dependencies: &[(String, Vec<ts_rs::Dependency>)]) {
    for (parent, deps) in dependencies {
        for dep in deps {
            assert!(
                emitted.contains(&dep.ts_name),
                "missing TypeScript declaration {} referenced by {}: add it to emit!",
                dep.ts_name,
                parent
            );
        }
    }
}

fn main() {
    let config = Config::default();
    let mut declarations = Vec::new();
    let mut emitted = HashSet::new();
    let mut dependencies = Vec::new();
    println!(
        "// Generated by `make generate-swap-types`; do not edit.\n\
        // u64/i64 responses are bigint; u32/u8 are number.\n\
        // Option fields become optional: serde-wasm-bindgen emits undefined.\n"
    );
    macro_rules! emit {
        ($($ty:ty),* $(,)?) => {$({
            emitted.insert(<$ty>::ident(&config));
            dependencies.push((<$ty>::name(&config), <$ty>::dependencies(&config)));
            let declaration = <$ty>::decl(&config);
            // serde-wasm-bindgen accepts both safe JS Numbers and BigInts in
            // request objects. Responses always use BigInt for 64-bit values.
            let declaration = if <$ty>::name(&config).ends_with("Request") {
                declaration.replace("bigint", "(bigint | number)")
            } else {
                declaration
            };
            let declaration = declaration.lines().map(str::trim_end).collect::<Vec<_>>().join("\n");
            declarations.push(format!("export {declaration}"));
        })*};
    }
    emit!(
        Leaf,
        SwapTree,
        RgbLock,
        InternalHopRef,
        SubSwapStates,
        RevSwapStates,
        ChainSwapStates,
        Webhook<String>,
        CreateSubmarineRequest,
        CreateSubmarineResponse,
        CreateReverseRequest,
        CreateReverseResponse,
        CreateChainRequest,
        ChainSwapDetails,
        CreateChainResponse,
        TransactionResponse,
        TransactionOut,
        SwapEvent,
        SwapPayoutStatus,
        GetSwapResponse,
        ClaimDetails,
        RefundDetails,
        SwapRestoreType,
        SwapRestoreResponse,
        SwapRestoreIndexResponse,
    );
    assert_complete(&emitted, &dependencies);
    println!("{}", declarations.join("\n\n"));
}

#[cfg(test)]
mod tests {
    use super::*;
    #[derive(TS)]
    #[allow(dead_code)]
    struct Nested {
        amount: u64,
    }
    #[derive(TS)]
    #[allow(dead_code)]
    struct Parent {
        nested: Option<Nested>,
    }

    #[test]
    #[should_panic(expected = "missing TypeScript declaration Nested referenced by Parent")]
    fn missing_nested_declaration_fails_generation() {
        assert_complete(
            &HashSet::from([Parent::ident(&Config::default())]),
            &[(
                Parent::name(&Config::default()),
                Parent::dependencies(&Config::default()),
            )],
        );
    }
    #[test]
    fn complete_nested_declarations_pass() {
        assert_complete(
            &HashSet::from([
                Parent::ident(&Config::default()),
                Nested::ident(&Config::default()),
            ]),
            &[(
                Parent::name(&Config::default()),
                Parent::dependencies(&Config::default()),
            )],
        );
    }
}
